"""
stage4_case_builder.py — deterministic case synthesis for the Simulation stage.

Plain Python, ZERO model calls, ever. This module is substrate-side machinery:
although it lives in stages/ (per the Step-12 build order), it belongs to the
tool-wrapper layer conceptually — it is the one place above tools/run_cfd.py
that legitimately knows the substrate's file formats, because writing case
files IS the substrate. Stage code (stage4_simulation.py) only calls
build_case() and never reads or names what is written here.

build_case(spec_run_params, case_name) copies cases/cavity_baseline/ as a
template — ONLY its clean {0/, constant/, system/} subtrees, never the
baseline's own run artifacts (time dirs, logs, postProcessing/), and never
constant/polyMesh, because the mesh is always regenerated by blockMesh as
part of synthesis — then rewrites exactly the files the supported parameters
require, and finally runs blockMesh inside the production container.

The honesty contract (load-bearing): the FULL parameter dict of one
mini-experiment run is partitioned into
  (a) buildable — the ONLY parameters this builder may honor (BUILDABLE_PARAMS)
  (b) explicitly ignorable — pure bookkeeping with no physical effect; the
      list starts EMPTY and stays empty until a real parameter earns a place
  (c) everything else — CaseSynthesisError naming every unsupported parameter.
reynolds_number is NOT buildable directly: supplied alongside an explicit
lid_velocity + cavity_length + kinematic_viscosity decomposition it is
VERIFIED (Re = U*L/nu within 1%) and the build proceeds; inconsistent, it
halts with the numbers; supplied without the full explicit decomposition it
halts — this builder never invents a decomposition.

Step 16 (derived-parameter convention): parameters the SPEC declared with
role "derived" (delivered via the roles map, never guessed) are excluded
from the buildable-set check when they appear in run dicts — but never
waved through: the builder has exactly ONE verifiable rule today, the
Reynolds decomposition. A derived parameter qualifies iff its derived_from
string names all of lid_velocity, cavity_length, kinematic_viscosity; it is
then verified against U*L/nu computed from that run dict's own values
(within 1%, halt on mismatch). Any other derived rule halts by name — an
unverified derived claim is the converged-but-wrong seed, and halting is
the honest behavior.
"""

from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path

from tools.run_cfd import (
    CONTAINER,
    DOCKER_CONTEXT,
    OF_BASHRC,
    SHARED_CONTAINER,
    SHARED_HOST,
    TIMEOUT_SECONDS,
)

TEMPLATE = SHARED_HOST / "cavity_baseline"
TEMPLATE_SUBDIRS = ("0", "constant", "system")

# The ONLY spec parameters this builder may honor, and where each one lands.
BUILDABLE_PARAMS = (
    "kinematic_viscosity",  # -> constant/physicalProperties (nu)
    "lid_velocity",         # -> 0/U movingWall fixedValue vector
    "cavity_length",        # -> system/blockMeshDict vertices (uniform scaling)
    "mesh_resolution",      # -> system/blockMeshDict cell counts (N x N x 1)
    "end_time",             # -> system/controlDict endTime (+ writeInterval)
    "time_step",            # -> system/controlDict deltaT (+ writeInterval)
)

# Pure-bookkeeping parameters with no physical effect on the case. Deliberately
# EMPTY: nothing known today qualifies, and anything tempting belongs in a
# debrief asterisk, not here.
IGNORABLE_PARAMS: frozenset[str] = frozenset()

REYNOLDS_KEY = "reynolds_number"
REYNOLDS_TOLERANCE = 0.01  # relative: |Re_given - U*L/nu| / Re_given <= 1%

# The ONE derived rule this builder can verify today (Step 16): a derived
# parameter qualifies iff its derived_from string names all three of these.
DERIVED_DECOMPOSITION = ("lid_velocity", "cavity_length", "kinematic_viscosity")

# Case names are interpolated into a container shell line, so they are locked
# to plain path-safe characters — anything else is refused, never quoted in.
_CASE_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")

_MESH_ERROR_TAIL = 15  # bounded: how many log lines a blockMesh failure returns


class CaseSynthesisError(Exception):
    """An honest halt: this case cannot be built from these parameters."""


def _is_number(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def partition_params(
    params: dict, derived_names: frozenset[str] | set[str] = frozenset()
) -> tuple[dict, dict, list[str]]:
    """Split one run's full parameter dict into (buildable, ignored, unsupported).

    reynolds_number goes in neither bucket — it is handled by check_reynolds.
    Names in derived_names (spec-declared role "derived", Step 16) are
    likewise excluded here — check_derived owns their verification; exclusion
    without verification never happens. Pure function; raises nothing.
    """
    buildable: dict = {}
    ignored: dict = {}
    unsupported: list[str] = []
    for name, value in params.items():
        if name == REYNOLDS_KEY:
            continue
        elif name in derived_names:
            continue
        elif name in BUILDABLE_PARAMS:
            buildable[name] = value
        elif name in IGNORABLE_PARAMS:
            ignored[name] = value
        else:
            unsupported.append(name)
    return buildable, ignored, sorted(unsupported)


def check_reynolds(params: dict) -> None:
    """Enforce the reynolds_number honesty rule. Raises CaseSynthesisError."""
    if REYNOLDS_KEY not in params:
        return
    re_given = params[REYNOLDS_KEY]
    if not _is_number(re_given) or re_given <= 0:
        raise CaseSynthesisError(
            f"cannot build: reynolds_number must be a positive number; got {re_given!r}"
        )
    decomposition = ("lid_velocity", "cavity_length", "kinematic_viscosity")
    missing = [k for k in decomposition if k not in params]
    if missing:
        raise CaseSynthesisError(
            "cannot build: reynolds_number was supplied without an explicit "
            f"U/L/nu decomposition (missing {', '.join(missing)}) — the builder "
            "never invents a decomposition"
        )
    u, length, nu = (params[k] for k in decomposition)
    re_actual = u * length / nu
    if abs(re_given - re_actual) / re_given > REYNOLDS_TOLERANCE:
        raise CaseSynthesisError(
            f"cannot build: reynolds_number {re_given} is inconsistent with "
            f"U*L/nu = {u}*{length}/{nu} = {re_actual:g} (difference exceeds "
            f"{REYNOLDS_TOLERANCE:.0%})"
        )


def check_derived(params: dict, roles: dict, derived_names: set[str]) -> None:
    """Verify every spec-declared derived parameter present in this run dict
    (Step 16). Raises CaseSynthesisError; verifies, never invents.

    Qualification: the derived_from rule string must name all three of
    DERIVED_DECOMPOSITION — the one rule this builder can verify today.
    Qualifying: the declared value must match lid_velocity * cavity_length /
    kinematic_viscosity computed from this run dict's own values within
    REYNOLDS_TOLERANCE. Anything else halts loudly by name: an unverified
    derived claim is the converged-but-wrong seed. reynolds_number itself is
    exempt here — check_reynolds already owns exactly that verification.
    """
    for name in sorted(derived_names):
        if name not in params or name == REYNOLDS_KEY:
            continue
        rule = roles.get(name, {}).get("derived_from")
        rule_text = rule if isinstance(rule, str) else ""
        if not all(part in rule_text for part in DERIVED_DECOMPOSITION):
            raise CaseSynthesisError(
                f"cannot build: derived parameter {name}: rule not verifiable by "
                f"this builder (the only verifiable rule today is the Reynolds "
                f"decomposition naming {', '.join(DERIVED_DECOMPOSITION)}; "
                f"derived_from was {rule!r})"
            )
        declared = params[name]
        if not _is_number(declared) or declared <= 0:
            raise CaseSynthesisError(
                f"cannot build: derived parameter {name} must be a positive "
                f"number to verify; got {declared!r}"
            )
        missing = [
            k for k in DERIVED_DECOMPOSITION if not _is_number(params.get(k))
        ]
        if missing:
            raise CaseSynthesisError(
                f"cannot build: derived parameter {name} cannot be verified — "
                f"this run dict is missing numeric {', '.join(missing)}"
            )
        u, length, nu = (params[k] for k in DERIVED_DECOMPOSITION)
        computed = u * length / nu
        if abs(declared - computed) / declared > REYNOLDS_TOLERANCE:
            raise CaseSynthesisError(
                f"cannot build: derived parameter {name} declared {declared} but "
                f"its rule computes lid_velocity*cavity_length/"
                f"kinematic_viscosity = {u}*{length}/{nu} = {computed:g} "
                f"(difference exceeds {REYNOLDS_TOLERANCE:.0%})"
            )


def _validate_buildable_values(buildable: dict) -> None:
    """Type/positivity checks on the honored parameters. Raises CaseSynthesisError."""
    positive = ("kinematic_viscosity", "cavity_length", "end_time", "time_step")
    for name in positive:
        if name in buildable:
            value = buildable[name]
            if not _is_number(value) or value <= 0:
                raise CaseSynthesisError(
                    f"cannot build: {name} must be a positive number; got {value!r}"
                )
    if "lid_velocity" in buildable and not _is_number(buildable["lid_velocity"]):
        raise CaseSynthesisError(
            f"cannot build: lid_velocity must be a number; got {buildable['lid_velocity']!r}"
        )
    if "mesh_resolution" in buildable:
        n = buildable["mesh_resolution"]
        ok = (isinstance(n, int) and not isinstance(n, bool) and n >= 1) or (
            isinstance(n, float) and n.is_integer() and n >= 1
        )
        if not ok:
            raise CaseSynthesisError(
                f"cannot build: mesh_resolution must be a whole number >= 1; got {n!r}"
            )


def _sub_exactly_once(pattern: str, replacement: str, text: str, where: str) -> str:
    new_text, count = re.subn(pattern, replacement, text, flags=re.MULTILINE)
    if count != 1:
        raise CaseSynthesisError(
            f"cannot build: template rewrite of {where} matched {count} times "
            "(expected exactly 1) — the template no longer looks like the "
            "baseline this builder was written against"
        )
    return new_text


def _fmt(value: float) -> str:
    return f"{value:g}"


def _rewrite_viscosity(case_dir: Path, nu: float) -> None:
    path = case_dir / "constant" / "physicalProperties"
    text = _sub_exactly_once(
        r"^(nu\s+)[0-9.eE+-]+(\s*\[[^\]]*\];)",
        rf"\g<1>{_fmt(nu)}\g<2>",
        path.read_text(),
        "constant/physicalProperties nu",
    )
    path.write_text(text)


def _rewrite_lid_velocity(case_dir: Path, u: float) -> None:
    # The template's only `value uniform (...)` entry is the movingWall lid;
    # internalField uses a different keyword, so exactly-once is a real check.
    path = case_dir / "0" / "U"
    text = _sub_exactly_once(
        r"^(\s*value\s+uniform\s+\()[^)]*(\);)",
        rf"\g<1>{_fmt(u)} 0 0\g<2>",
        path.read_text(),
        "0/U movingWall value",
    )
    path.write_text(text)


def _rewrite_blockmesh(case_dir: Path, length: float | None, cells: int | None) -> None:
    path = case_dir / "system" / "blockMeshDict"
    text = path.read_text()

    if length is not None:
        # Uniform scaling of the unit cavity: every vertex coordinate
        # (including the thin z depth) is multiplied by cavity_length.
        match = re.search(r"vertices\s*\((.*?)\);", text, flags=re.DOTALL)
        if not match:
            raise CaseSynthesisError(
                "cannot build: template blockMeshDict has no vertices block"
            )
        block = match.group(1)
        scaled, count = re.subn(
            r"\(\s*([0-9.eE+-]+)\s+([0-9.eE+-]+)\s+([0-9.eE+-]+)\s*\)",
            lambda m: "("
            + " ".join(_fmt(float(m.group(i)) * length) for i in (1, 2, 3))
            + ")",
            block,
        )
        if count != 8:
            raise CaseSynthesisError(
                f"cannot build: expected 8 vertices in the template blockMeshDict, "
                f"found {count}"
            )
        text = text[: match.start(1)] + scaled + text[match.end(1) :]

    if cells is not None:
        cells = int(cells)
        text = _sub_exactly_once(
            r"(hex\s*\([^)]*\)\s*\()\s*\d+\s+\d+\s+\d+\s*(\))",
            rf"\g<1>{cells} {cells} 1\g<2>",
            text,
            "system/blockMeshDict cell counts",
        )

    path.write_text(text)


def _rewrite_control_dict(case_dir: Path, end_time: float | None, time_step: float | None) -> None:
    path = case_dir / "system" / "controlDict"
    text = path.read_text()

    def current(key: str) -> float:
        m = re.search(rf"^\s*{key}\s+([0-9.eE+-]+);", text, flags=re.MULTILINE)
        if not m:
            raise CaseSynthesisError(f"cannot build: template controlDict has no {key}")
        return float(m.group(1))

    new_end = end_time if end_time is not None else current("endTime")
    new_dt = time_step if time_step is not None else current("deltaT")

    # writeControl stays timeStep (the template's proven mode); writeInterval is
    # set to the exact step count so the final time directory is written. That
    # requires end_time to be a whole number of time_steps — anything else
    # cannot guarantee the final write, so it is an honest halt, not a guess.
    ratio = new_end / new_dt
    steps = round(ratio)
    if steps < 1 or abs(ratio - steps) > 1e-6 * max(1.0, ratio):
        raise CaseSynthesisError(
            f"cannot build: end_time {new_end} is not a whole number of "
            f"time_steps {new_dt} (ratio {ratio:g}) — the final time directory "
            "could not be guaranteed"
        )

    text = _sub_exactly_once(
        r"^(endTime\s+)[0-9.eE+-]+;", rf"\g<1>{_fmt(new_end)};", text, "controlDict endTime"
    )
    text = _sub_exactly_once(
        r"^(deltaT\s+)[0-9.eE+-]+;", rf"\g<1>{_fmt(new_dt)};", text, "controlDict deltaT"
    )
    text = _sub_exactly_once(
        r"^(writeInterval\s+)[0-9.eE+-]+;",
        rf"\g<1>{steps};",
        text,
        "controlDict writeInterval",
    )
    path.write_text(text)


def _copy_template(template: Path, case_dir: Path) -> None:
    """Copy ONLY the clean {0/, constant/, system/} subtrees, minus polyMesh.

    The baseline carries its own Step-11 run artifacts (time dirs, logs,
    postProcessing/) — copying those would seed a synthesized case with stale
    results that -latestTime QoI extraction could silently read. polyMesh is
    excluded because blockMesh regenerates the mesh as part of synthesis.
    """
    for sub in TEMPLATE_SUBDIRS:
        src = template / sub
        if not src.is_dir():
            raise CaseSynthesisError(
                f"cannot build: template {template} is missing its {sub}/ subtree"
            )
        shutil.copytree(src, case_dir / sub, ignore=shutil.ignore_patterns("polyMesh"))


def _run_blockmesh(case_name: str) -> None:
    remote = (
        f"source {OF_BASHRC} && cd {SHARED_CONTAINER}/{case_name} && "
        "blockMesh > log.blockMesh 2>&1"
    )
    cmd = ["docker", "--context", DOCKER_CONTEXT, "exec", CONTAINER, "bash", "-c", remote]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=TIMEOUT_SECONDS)
    except subprocess.TimeoutExpired:
        raise CaseSynthesisError(
            f"cannot build: blockMesh exceeded {TIMEOUT_SECONDS}s timeout and was killed"
        )
    if proc.returncode != 0:
        log_path = SHARED_HOST / case_name / "log.blockMesh"
        if log_path.is_file():
            tail = [
                s.rstrip()
                for s in log_path.read_text(errors="replace").splitlines()
                if s.strip()
            ][-_MESH_ERROR_TAIL:]
        else:
            tail = proc.stderr.strip().splitlines()[-_MESH_ERROR_TAIL:]
        raise CaseSynthesisError(
            f"cannot build: blockMesh failed (exit {proc.returncode}): "
            + " | ".join(tail)
        )


def build_case(
    spec_run_params: dict,
    case_name: str,
    *,
    roles: dict | None = None,
    template: Path = TEMPLATE,
    cases_root: Path = SHARED_HOST,
    run_mesh: bool = True,
) -> Path:
    """Synthesize one runnable case under cases/ from one mini-experiment run's
    FULL parameter dict. Returns the case directory. Raises CaseSynthesisError
    on any honest halt. roles (Step 16) is the spec's {name: {role,
    derived_from?}} map — parameters it declares "derived" skip the
    buildable-set check and are verified by check_derived instead; omitted,
    behavior is exactly pre-Step-16. template/cases_root/run_mesh are test
    seams only — production callers use the defaults (run_mesh needs the
    container's bind mount, so it requires the default cases_root).
    """
    if not isinstance(spec_run_params, dict):
        raise CaseSynthesisError("cannot build: run parameters must be a dict")
    if not _CASE_NAME_RE.match(case_name or ""):
        raise CaseSynthesisError(
            f"cannot build: case name {case_name!r} is not a plain path-safe name"
        )
    if run_mesh and cases_root != SHARED_HOST:
        raise ValueError("run_mesh=True requires the default cases_root (container bind mount)")

    roles = roles if isinstance(roles, dict) else {}
    derived_names = {
        name
        for name, entry in roles.items()
        if isinstance(entry, dict) and entry.get("role") == "derived"
    }
    buildable, _ignored, unsupported = partition_params(spec_run_params, derived_names)
    if unsupported:
        raise CaseSynthesisError(
            f"cannot build: {', '.join(unsupported)} not in the buildable set "
            f"({', '.join(BUILDABLE_PARAMS)})"
        )
    _validate_buildable_values(buildable)
    check_reynolds(spec_run_params)
    check_derived(spec_run_params, roles, derived_names)

    case_dir = cases_root / case_name
    if case_dir.exists():
        raise CaseSynthesisError(
            f"cannot build: case directory {case_dir} already exists — refusing to overwrite"
        )
    _copy_template(template, case_dir)

    if "kinematic_viscosity" in buildable:
        _rewrite_viscosity(case_dir, buildable["kinematic_viscosity"])
    if "lid_velocity" in buildable:
        _rewrite_lid_velocity(case_dir, buildable["lid_velocity"])
    if "cavity_length" in buildable or "mesh_resolution" in buildable:
        _rewrite_blockmesh(
            case_dir,
            buildable.get("cavity_length"),
            buildable.get("mesh_resolution"),
        )
    if "end_time" in buildable or "time_step" in buildable:
        _rewrite_control_dict(
            case_dir, buildable.get("end_time"), buildable.get("time_step")
        )

    if run_mesh:
        _run_blockmesh(case_name)
    return case_dir
