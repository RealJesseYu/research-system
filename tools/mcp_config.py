"""mcp_config.py — the ONE reader of mcp_servers.json.

Two very different consumers read that file, and the whole connector bridge
rests on them reading the SAME definition:

  * `model_call.py` hands the map to the SDK so a FREE AGENT can REACH a
    connector — exploration, discovery, "go look it up".
  * `tools/run_mcp_tool.py` connects to the same server from deterministic
    Python with no model anywhere, so a connector's answer can be RE-RUN by
    `stages/verification.py` and therefore KEPT.

If those two ever read different files (or different keys of the same file),
a verified claim would be regenerated by something other than the connector
that produced it — which is precisely the fabrication the verification pass
exists to catch. Hence one module.

THE `_verifiable` DECLARATION (R-MCP-2; docs/memo_connector_bridge.md).
Verification purity is absolute: no model may enter the verification path. An
MCP server is an arbitrary process, and some MCP servers ARE language models
(a "research assistant" connector, an agentic search service). Re-running one
of those inside verification would put a model back in the one place the
project forbids it — silently, with no code change, just a config edit.

So a connector may back a KEPT NUMBER only when the human who configured it
declares it a deterministic data source, by writing `"_verifiable": true` in
that server's config block. Undeclared connectors still work for exploration
at full strength; their results can only ever be honest unverified caveats.
The declaration is a human governance act recorded in config, which is the
right place for a claim no code can check from the inside.

EXTENSION KEYS. Anything this project adds to a server block is `_`-prefixed
(`_verifiable`, `_description`) and is STRIPPED before the map reaches the SDK,
so the SDK only ever sees `McpServerConfig` fields it knows. Top-level
`_`-prefixed NAMES are comments (the example file's `_comment` and
`_example_*` entries) and are dropped from the server map entirely — without
this, `mcp_servers.example.json` copied verbatim would ask the SDK to launch
two servers named `_example_...`.

NEVER RAISES on a bad config. A broken connector file must not take down every
run in the project; it degrades to "no connectors", exactly as an absent file
does.
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path

_PROJECT_ROOT = Path(__file__).resolve().parent.parent

# The connector config. Gitignored: it may carry URLs and API keys.
CONFIG_PATH = _PROJECT_ROOT / "mcp_servers.json"

# The operator's declaration that a server is a deterministic data source and
# so may back a verified claim. See the module docstring.
VERIFIABLE_KEY = "_verifiable"

# An optional one-line human description, shown to the free agent so it knows
# what the connector is for without having to call it to find out.
DESCRIPTION_KEY = "_description"

# ${VAR} references in config strings are resolved from the environment, so a
# key lives in .env / the shell rather than in the config file. Deliberately
# ${...}-only: a bare `$` in a URL, header or argument is left alone.
_ENV_REF = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}")


def _expand(value):
    """Resolve ${VAR} references anywhere in a config value (recursively through
    dicts and lists). An unset variable expands to the empty string, matching
    shell behavior; the caller sees a failed connection rather than a silently
    different one, because an empty credential does not authenticate."""
    if isinstance(value, str):
        return _ENV_REF.sub(lambda m: os.environ.get(m.group(1), ""), value)
    if isinstance(value, dict):
        return {k: _expand(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_expand(v) for v in value]
    return value


def load_servers(path=None) -> dict:
    """The {name: config} connector map as written, extension keys INTACT and
    ${VAR} references unresolved. {} when the file is absent, empty, malformed,
    or holds no server blocks. Never raises.

    Comment entries (top-level names starting with '_') are dropped: they are
    documentation, not servers.
    """
    p = Path(path) if path else CONFIG_PATH
    try:
        if not p.is_file():
            return {}
        data = json.loads(p.read_text())
    except (OSError, ValueError):
        return {}
    # Tolerate either a bare {name: config} map or {"servers": {...}}.
    if isinstance(data, dict) and isinstance(data.get("servers"), dict):
        data = data["servers"]
    if not isinstance(data, dict):
        return {}
    return {
        name: cfg for name, cfg in data.items()
        if isinstance(name, str) and not name.startswith("_")
        and isinstance(cfg, dict)
    }


def sdk_servers(path=None) -> dict:
    """The connector map as the SDK must receive it: extension keys stripped,
    nothing else changed. ${VAR} is left for the SDK/CLI to resolve, which is
    what it did before this module existed — the SDK path stays byte-identical
    for any config that carries no extension keys."""
    return {
        name: {k: v for k, v in cfg.items() if not k.startswith("_")}
        for name, cfg in load_servers(path).items()
    }


def server_config(name: str, path=None) -> dict | None:
    """One connector's config with ${VAR} references RESOLVED, ready for the
    deterministic client to connect with, or None when no such server is
    configured. Extension keys are kept — the caller needs `_verifiable`."""
    cfg = load_servers(path).get(name)
    return _expand(cfg) if cfg is not None else None


def is_verifiable(name: str, path=None) -> bool:
    """True only when this server's config declares `"_verifiable": true` — the
    human's assertion that it is a deterministic data source with no model
    inside it (R-MCP-2). Anything else — absent, false, "yes", 1 — is False:
    a claim-bearing declaration is never inferred, only read."""
    cfg = load_servers(path).get(name) or {}
    return cfg.get(VERIFIABLE_KEY) is True


def connector_catalog(path=None) -> str:
    """The model-visible block naming this run's configured connectors and how
    to turn one's answer into a KEPT number. Empty string when none are
    configured, so a run with no connectors composes a byte-identical prompt.

    This is INFORMATION, not a boundary (PRIME DIRECTIVE): the agent already
    sees each server's tools natively as `mcp__<name>__<tool>` and may call them
    freely. What it cannot discover on its own is the artifact shape that lets a
    connector-derived number survive verification — that is what this block
    carries.
    """
    servers = load_servers(path)
    if not servers:
        return ""
    lines = [
        "CONNECTORS (MCP) configured for this run — you can call each one's "
        "tools directly as mcp__<server>__<tool>:",
    ]
    for name, cfg in servers.items():
        desc = str(cfg.get(DESCRIPTION_KEY) or "").strip()
        if cfg.get(VERIFIABLE_KEY) is True:
            tag = ("KEEPABLE: declared a deterministic data source, so a number "
                   "from it can be a verified result")
        else:
            tag = ("EXPLORATION ONLY: not declared a deterministic data source, "
                   "so anything from it must be reported with \"verified\": false")
        lines.append(f"- {name}" + (f" — {desc}" if desc else "") + f"  [{tag}]")
    lines.append(
        "\nTO KEEP A NUMBER A CONNECTOR GAVE YOU, do NOT copy it into a Python "
        "file — a value written into source is rejected as a hardcoded constant, "
        "however true it is. Name the connector CALL itself as the artifact:\n"
        '  "artifact": {"substrate_id": "mcp_connector", "typed_input": '
        '{"server": "<server>", "tool": "<tool name WITHOUT the mcp__<server>__ '
        'prefix>", "arguments": {<exactly what you passed>}, "select": "<dotted '
        'path to the number inside the tool\'s result, e.g. value or '
        'properties.0.MolecularWeight>"}, "quantity": "<what it measures>"}\n'
        "An independent pass with NO model in it then re-calls that exact tool "
        "and must get your number back. Check your select path first by calling "
        "`from tools.run_mcp_tool import run_mcp_tool` in Bash with the same "
        "typed_input — it returns the number the verifier will see. A connector "
        "value you cannot back this way is an honest caveat, not a claim."
    )
    return "\n".join(lines)
