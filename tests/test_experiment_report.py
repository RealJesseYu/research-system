"""test_experiment_report.py — the deterministic routed-run write-up (R-ROUTE-5).

docs/memo_phase3_routing.md. A routed exact-tool run's paper is generated by code
from the verified investigation — no model — so it can only state numbers the
verifier reproduced. These tests pin: a verified number appears with its recipe;
an unreproduced probe is listed but NOT given a value; the publishable verdict is
honest; and the nothing-ran case does not pretend to stand.

Run directly: venv/bin/python3 tests/test_experiment_report.py
"""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import shutil  # noqa: E402

from stages.experiment_report import render_report, write_report  # noqa: E402


def _recipe():
    return {"kind": "composition",
            "steps": [{"step_id": "growth", "kind": "substrate",
                       "substrate_id": "cobrapy",
                       "typed_input": {"model": "e_coli_core",
                                       "quantity": "growth_rate"},
                       "quantity": "growth_rate"},
                      {"step_id": "mass", "kind": "substrate",
                       "substrate_id": "rdkit",
                       "typed_input": {"smiles": "CCO", "quantity": "MolWt"},
                       "quantity": "MolWt"}],
            "combine": {"kind": "code",
                        "code": "metrics['gpm'] = inputs['growth']/inputs['mass']",
                        "quantity": "gpm", "inputs": ["growth", "mass"]}}


def _verified_result():
    return {
        "fidelity": {"applies": False, "instrument_class": "exact",
                     "reason": "exact-tool investigation: re-running IS the check"},
        "publishable": True,
        "investigation": {
            "iterations": 1, "verified": 1, "total": 1, "publishable": True,
            "stop_reason": "reproduced; enough",
            "measurements": [{
                "iteration": 0, "recipe": _recipe(), "value": 0.0191,
                "verified": True, "reason": "reproduced", "rel_error": 0.0,
                "predicted": 0.02, "prediction_abs_error": 0.0009,
                "reasoning": "growth per unit mass",
            }],
        },
    }


class TestVerifiedRunReport(unittest.TestCase):
    def test_it_states_the_verified_number_with_its_recipe(self):
        md = render_report(_verified_result())
        self.assertIn("Publishable", md)
        self.assertIn("0.0191", md)          # the verified number of record
        self.assertIn("Verified result", md)
        self.assertIn("cobrapy", md)         # the recipe wiring is shown
        self.assertIn("rdkit", md)

    def test_the_fidelity_skip_is_reported(self):
        md = render_report(_verified_result())
        self.assertIn("fidelity gate did not fire", md)

    def test_a_prediction_is_shown_as_a_prediction_not_the_result(self):
        md = render_report(_verified_result())
        self.assertIn("prediction is compared, never recorded", md)


class TestUnreproducedIsNotClaimed(unittest.TestCase):
    def test_an_unverified_probe_gets_no_number(self):
        result = _verified_result()
        m = result["investigation"]["measurements"][0]
        m["verified"] = False
        m["reason"] = "mismatch"
        m["value"] = 0.0191  # even with a value present, it must not be claimed
        result["publishable"] = False
        result["investigation"]["verified"] = 0
        result["investigation"]["publishable"] = False
        md = render_report(result)
        self.assertIn("NOT claimed", md)
        self.assertIn("did not reproduce", md)
        self.assertIn("Does not stand", md)


class TestWriteToDisk(unittest.TestCase):
    def test_it_writes_the_md_and_json_when_the_run_dir_exists(self):
        run_id = "report-disk-test"
        run_dir = ROOT / "runs" / run_id
        run_dir.mkdir(parents=True, exist_ok=True)
        try:
            path = write_report(_verified_result(), run_id)
            self.assertTrue(path.exists())
            self.assertEqual(path.name, "exact_route_report.md")
            self.assertIn("Verified result", path.read_text())
            self.assertTrue((run_dir / "exact_route_report.json").exists())
        finally:
            shutil.rmtree(run_dir, ignore_errors=True)

    def test_it_no_ops_when_the_run_dir_is_absent(self):
        self.assertIsNone(write_report(_verified_result(), "no-such-run-dir-xyz"))


class TestNothingRan(unittest.TestCase):
    def test_a_run_with_no_probes_does_not_pretend_to_stand(self):
        result = {"fidelity": {"reason": "exact"}, "publishable": False,
                  "investigation": {"iterations": 0, "verified": 0, "total": 0,
                                    "measurements": [], "publishable": False,
                                    "stop_reason": "nothing to do"}}
        md = render_report(result)
        self.assertIn("Does not stand", md)
        self.assertIn("No probe ran", md)


if __name__ == "__main__":
    unittest.main()
