# ---------------------------------------------------------------------------
# MOVE TOKEN ALLOWANCE (item A, 2026-07-28): make the ceiling bind INSIDE a
# move. The director's token budget was checked only BETWEEN moves, and one
# free-experimenter move is an agentic loop of up to 200 turns — so a single
# move sailed 58% past a 5M budget (study-20260728T152819Z: spent 7,900,340).
#
# The director passes each dispatched run its remaining allowance via this env
# var (pi_agent/free_director.py). Inside the run, THREE layers make it bind,
# in order of grace:
#   1. WIND-UP, not guillotine: a per-call tracker watches the SDK stream
#      (turns, and real per-message usage when present); once the allowance is
#      reached — or the granted turns enter the wind-up reserve — further TOOL
#      calls are denied with a message telling the agent to write its honest
#      final answer now. The agent keeps its context and finishes deliberately;
#      a denial is feedback, not a model call.
#   2. STRUCTURAL BOUND: each tooled call's max_turns is derived from the
#      remaining allowance (remaining // EST_TOKENS_PER_TURN, floored at
#      MIN_GRANTED_TURNS, capped at the profile's own ceiling), so even with no
#      usage data in the stream the loop cannot run 200 turns on a 500k
#      allowance.
#   3. PRE-ATTEMPT CHECK: a new attempt (including validation re-asks) with the
#      allowance already spent raises TokenAllowanceExhausted instead of
#      burning another full agentic run; the supervisor journals it as an
#      honest halted_token_allowance run_record — a RECORDED result the
#      director reads, never a silent truncation.
#
# OVERSHOOT BOUND, stated: with per-message usage present the trip fires on the
# turn that crosses the allowance, and everything after is wind-up — at most
# (WIND_UP_RESERVE_TURNS + denied-tool turns up to the derived max_turns) of
# context re-reads plus text output, with no new tool results. Without usage
# data the structural bound holds: total spend <= derived max_turns x the
# call's actual per-turn cost, i.e. overshoot is bounded by the estimate error
# (actual/EST - 1) x remaining, plus the MIN_GRANTED_TURNS floor. It is a
# bounded honest ceiling, not a hard wall — a killed move that reports success
# would be worse than either.
#
# No model call anywhere in this machinery; everything is deterministic Python
# reading the same face-value token units the director's budget already uses.
# ---------------------------------------------------------------------------

MOVE_ALLOWANCE_ENV = "RESEARCH_MOVE_TOKEN_ALLOWANCE"

# Face-value tokens per agentic turn, measured: study-20260728T152819Z recorded
# 7,851,857 face-value tokens across 2 FULL calls of ~200 turns each — ~20k per
# turn. Used only to DERIVE a turn ceiling from a token allowance; the in-stream
# tracker uses real usage when the SDK reports it.
EST_TOKENS_PER_TURN = 20_000

# Even a nearly-spent allowance grants a few turns: an agent that cannot take
# any turn cannot even report honestly. The pre-attempt check (not this floor)
# is what refuses a call once the allowance is fully gone.
MIN_GRANTED_TURNS = 8

# Turns held back from the granted ceiling for winding up: the soft stop fires
# this many turns BEFORE the hard SDK max_turns, so the agent finishes its
# answer inside the granted budget instead of being cut off mid-JSON.
WIND_UP_RESERVE_TURNS = 4


class TokenAllowanceExhausted(RuntimeError):
    """The move's token allowance is spent before another model attempt could
    start. A distinct type so the supervisor can journal an honest
    halted_token_allowance run_record instead of a generic crash."""


def _move_token_allowance() -> Optional[int]:
    """The move's token allowance from the environment, or None when the
    dispatching director set none (the default: nothing changes). Malformed
    values read as None — a broken knob must widen, never cage."""
    raw = os.environ.get(MOVE_ALLOWANCE_ENV)
    if not raw:
        return None
    try:
        value = int(raw)
    except (TypeError, ValueError):
        return None
    return value if value > 0 else None


def in_process_allowance_ceiling(room_tokens: Optional[int]) -> Optional[int]:
    """The value to put in MOVE_ALLOWANCE_ENV so a call made IN THIS PROCESS
    gets `room_tokens` of room.

    The env var is an absolute ceiling on the READING PROCESS's face-value
    spend, not a per-call delta: every layer compares it against
    `_face_value_spent()`, which is this process's whole meter. A dispatched
    move runs in a fresh subprocess whose meter starts at zero, so there
    "remaining budget" and "ceiling" are the same number and the distinction
    never showed. An in-process capability runs inside a director that has
    already spent, so handing it the bare remaining budget would read as
    already-exhausted. Its ceiling is what is on the meter NOW plus its room.

    None (no room, or a broken meter) means no allowance — unknown must widen,
    never cage. Never raises."""
    try:
        room = int(room_tokens or 0)
    except (TypeError, ValueError):
        return None
    if room <= 0:
        return None
    return _face_value_spent() + room


def _face_value_spent() -> int:
    """This process's face-value token spend so far (the same
    sum-of-every-usage-field unit the director's budget check uses). Never
    raises; a broken meter reads as 0, which DISABLES the allowance rather
    than fabricating exhaustion — unknown must not cage the agent."""
    try:
        snap = cost_meter.read()
        return sum(v for v in snap.get("tokens", {}).get("total", {}).values()
                   if isinstance(v, int) and not isinstance(v, bool))
    except Exception:  # noqa: BLE001
        return 0


def _raise_if_allowance_exhausted(stage_name: str, attempt: int) -> None:
    """Layer 3: refuse to START another model attempt once the allowance is
    spent. No-op without the env var. Raising here — before the SDK call —
    is what stops a validation re-ask from burning another full agentic run
    on a budget that is already gone."""
    allowance = _move_token_allowance()
    if allowance is None:
        return
    spent = _face_value_spent()
    if spent >= allowance:
        raise TokenAllowanceExhausted(
            f"move token allowance spent: {spent:,} of {allowance:,} face-value "
            f"tokens used before stage {stage_name!r} attempt {attempt} could "
            "start. This is the director's per-move ceiling binding inside the "
            "move — an honest stop, not a model or transport failure."
        )


def _derive_granted_turns(remaining_tokens: int, profile_max_turns: int) -> int:
    """Layer 2: the turn ceiling a tooled call gets for `remaining_tokens` of
    allowance. Pure."""
    granted = remaining_tokens // EST_TOKENS_PER_TURN
    return max(MIN_GRANTED_TURNS, min(profile_max_turns, granted))


class _MoveBudgetTracker:
    """Layer 1's shared state: written by the stream consumer (_ask_once's
    message loop), read by the can_use_tool wrapper. Per-call, single
    event-loop — no lock needed."""

    def __init__(self, remaining_tokens: int, granted_turns: int,
                 wind_up_reserve: int = WIND_UP_RESERVE_TURNS):
        self.remaining_tokens = remaining_tokens
        self.granted_turns = granted_turns
        self.wind_up_reserve = wind_up_reserve
        self.tokens_seen = 0
        self.turns_seen = 0
        self.announced = False
        # A TURN IS ONE API MESSAGE (2026-07-30). See note_assistant_message.
        self._seen_message_ids: set = set()

    def note_assistant_message(self, usage, message_id=None) -> None:
        """One assistant TURN observed; accumulate its usage when the SDK
        reports it (face-value sum, same unit as the allowance).

        ONE API MESSAGE COUNTS ONCE (fixed 2026-07-30, owner-ruled). The SDK
        yields one `AssistantMessage` PER CONTENT BLOCK, and every block of one
        API message carries that message's identical `usage`. So this counted
        blocks as turns and re-added the same usage per block. Measured on
        study-20260730T034915Z move 16: 199 assistant events for **97 unique
        message ids** (blocks per message {2:47, 1:24, 3:23, 4:3}), so the turn
        wind-up tripped at "turn 197 of 200" after 97 real turns — less than half
        the granted budget — and `tokens_seen` reached 34.7M against a metered
        17.1M. Nine of that study's twelve completed moves were cut off this way,
        and m14/m15 tripped at "turn 230/221 of 200", which is the proof the
        counter was not counting turns. Full evidence:
        docs/finding_m16_stopping_mechanism.md.

        Dedup is on the SDK's `message_id`. When it is absent (an older SDK, a
        test fake calling this positionally) the pre-fix counting is unchanged —
        we cannot dedupe what we cannot identify, and guessing would be worse
        than the honest fallback.
        """
        if message_id is not None:
            if message_id in self._seen_message_ids:
                return  # same API message, another content block
            self._seen_message_ids.add(message_id)
        self.turns_seen += 1
        if isinstance(usage, dict):
            self.tokens_seen += sum(
                v for v in usage.values()
                if isinstance(v, int) and not isinstance(v, bool))

    def wind_up(self) -> Optional[tuple]:
        """(headline, detail) naming WHICH condition fired, or None while there
        is room.

        THE HEADLINE IS LOAD-BEARING (2026-07-30). _WIND_UP_MESSAGE used to
        hardcode "TOKEN ALLOWANCE EXHAUSTED" and interpolate a reason that might
        say "turn 197 of 200". So an agent stopped by the TURN reserve was told
        its token budget was gone, and reported that: m16 wrote "the token budget
        ran out" having spent 17.1M of 52.9M. It was quoting the harness
        faithfully. The two conditions must now be distinguishable by anyone —
        agent or human — reading the message.
        """
        if self.tokens_seen >= self.remaining_tokens:
            return (WIND_UP_TOKEN_HEADLINE,
                    f"measured in-call spend ({self.tokens_seen:,} face-value "
                    f"tokens) has reached this move's remaining allowance "
                    f"({self.remaining_tokens:,})")
        soft_stop = max(1, self.granted_turns - self.wind_up_reserve)
        if self.turns_seen >= soft_stop:
            return (WIND_UP_TURN_HEADLINE,
                    f"turn {self.turns_seen} of {self.granted_turns} granted for "
                    "this call — the remaining turns are the wind-up reserve. "
                    "This is a TURN limit, NOT a spend limit: this move's token "
                    f"allowance is NOT exhausted ({self.tokens_seen:,} of "
                    f"{self.remaining_tokens:,} seen), so do not report that you "
                    "ran out of budget")
        return None

    def wind_up_reason(self) -> Optional[str]:
        """The detail half of wind_up(), or None. Kept as its own name because
        callers and tests already use it; wind_up() is the fuller answer."""
        found = self.wind_up()
        return found[1] if found else None


# The two headlines a wind-up can carry. Separate constants because a test — and
# a human reading a log — must be able to tell the conditions apart, which is
# exactly what the single hardcoded headline made impossible.
WIND_UP_TURN_HEADLINE = "TURN BUDGET REACHED"
WIND_UP_TOKEN_HEADLINE = "TOKEN ALLOWANCE EXHAUSTED"

# Signal tags recorded on the meter when a wind-up fires, so the run_record can
# say a move was CUT OFF rather than finished (a director that cannot tell those
# apart cannot plan around either).
WIND_UP_SIGNAL = {
    WIND_UP_TURN_HEADLINE: "wind_up_turn_budget",
    WIND_UP_TOKEN_HEADLINE: "wind_up_token_allowance",
}

_WIND_UP_MESSAGE = (
    "{headline} for this move ({reason}). No further tool calls "
    "will be permitted in this call. Stop investigating now and write your "
    "final answer in the required JSON format: report honestly what you "
    "established and what you did not get to, mark anything you could not "
    "verify as verified: false, and do not invent results. State the reason you "
    "stopped ACCURATELY — it is the one printed above, not a reason you infer. "
    "An honest partial answer is the expected outcome here — the director reads "
    "it and decides what happens next. Anything you already emitted with "
    "tools.emit_finding.emit() is SAVED and is picked up automatically — you do "
    "not need to list it again and it is not lost. No tool call will be "
    "permitted now, so do not promise a file you have not already written; but "
    "for any number whose producer file you DID write, name that file as that "
    "finding's 'artifact' — that costs no tool call and it is the difference "
    "between a reproduced number and a caveat."
)
# WHY THIS SAYS "name a file you already wrote" AND NOT "write your producers
# now" (T0.2). The wind-up is the one moment the agent is guaranteed to be
# listening — and it is the one moment it can do nothing about it, because the
# same tracker that sends this message denies EVERY tool call (see the two
# wrappers below). m16's session transcript is the proof: a Write denied at
# 09:56:08Z carrying this exact text, immediately before its final JSON
# (docs/finding_m16_stopping_mechanism.md). Asking here for producers would ask
# for what the harness has just forbidden. The reserve is not widened to let one
# through, either: it exists to guarantee the final answer gets written, and an
# agent granted writes at wind-up can spend all of it emitting files and return
# nothing — losing everything instead of the tail. So the sequencing fix lives
# where it can actually work, EARLIER (stages/free_experimenter.py's emit
# affordance), and this message is limited to the two things that need no tool:
# tell it what is already safe, and tell it to name a file that already exists.


# The run whose model calls are being made right now, for the ONE observer that
# fires deep inside the SDK stream and so has no stage_input in scope: the
# wind-up. Set and cleared by call_stage_model around its attempt loop. Same
# process-global caveat as the transcript sequence counter — it belongs on the
# parallelization revisit list, and like that counter it is single-writer today
# because a dispatched run is its own process.
_CURRENT_RUN_ID: Optional[str] = None


def _announce_wind_up(tracker: "_MoveBudgetTracker", stage_name: str,
                      headline: str, reason: str) -> None:
    """Record a wind-up ONCE per call: terminal, run log, and the meter.

    IT ONLY print()ed BEFORE (fixed 2026-07-30). A move being CUT OFF left no
    trace on disk at all — not in the run's log.txt, not in its run_record — so
    a study where nine of twelve moves were truncated read as nine moves that
    chose to stop, and finding that out took a whole session of transcript
    archaeology. Never raises: an observer may not sink a run.
    """
    if tracker.announced:
        return
    tracker.announced = True
    line = (f"WIND_UP stage={stage_name} {headline} — {reason}; further tool "
            "calls denied, agent told to finish honestly")
    print(line)
    try:
        # Durable, beside RE-ASK and the fence NOTE, via the same run_id-derived
        # path (and the same limitation: a bare call with no run_id prints only).
        _append_run_log({"run_id": _CURRENT_RUN_ID}, line)
    except Exception:  # noqa: BLE001
        pass
    try:
        # And onto the meter, which is how it reaches the run_record: the
        # supervisor reads the same snapshot it already reads for cost.
        cost_meter.record_signal(WIND_UP_SIGNAL.get(headline, "wind_up"))
    except Exception:  # noqa: BLE001
        pass


def _wrap_can_use_tool_with_allowance(inner, tracker: "_MoveBudgetTracker",
                                      stage_name: str):
    """Layer 1: deny tool calls once the tracker says the move must wind up;
    delegate to the stage's own capability guard otherwise. The denial message
    is feedback the agent reads in-context — no model call is added."""
    from claude_agent_sdk import PermissionResultDeny

    async def can_use_tool(tool_name: str, tool_input: dict, context):
        found = tracker.wind_up()
        if found is None:
            return await inner(tool_name, tool_input, context)
        headline, reason = found
        _announce_wind_up(tracker, stage_name, headline, reason)
        return PermissionResultDeny(
            message=_WIND_UP_MESSAGE.format(headline=headline, reason=reason))

    return can_use_tool


def _wrap_hook_with_allowance(inner, tracker: "_MoveBudgetTracker",
                              stage_name: str):
    """Layer 1, delivered where the SDK actually calls it.

    Same policy as _wrap_can_use_tool_with_allowance and the same order (the
    wind-up decides first, the capability guard otherwise), but returning the
    PreToolUse hook's decision object rather than a PermissionResult. The
    callback version above is kept for tools that are NOT on allowed_tools;
    this is the one that fires for the experimenter's Bash/Write/Edit, because
    those ARE on the allowlist and so never reach a permission prompt.

    Never raises: an accounting wrapper may not end a run, so a tracker that
    somehow throws falls through to the inner guard.
    """

    async def pre_tool_use(hook_input, tool_use_id, context):
        try:
            found = tracker.wind_up()
        except Exception:  # noqa: BLE001
            found = None
        if found is None:
            return await inner(hook_input, tool_use_id, context)
        headline, reason = found
        _announce_wind_up(tracker, stage_name, headline, reason)
        return {
            "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "deny",
                "permissionDecisionReason":
                    _WIND_UP_MESSAGE.format(headline=headline, reason=reason),
            }
        }

    return pre_tool_use


class TransportFailure(RuntimeError):
    """The SDK reported the call itself failed, or it produced no text at all.

    A distinct type so it reads correctly in a log and cannot be mistaken for a
    content problem. It is raised from inside _invoke_transport's callee, which
    puts it in _transport_with_retry's path — the code that knows a sealed call
    may be replayed and a TOOLED one may not.
    """


def _raise_if_transport_failed(result_message, caps) -> None:
    """Raise TransportFailure when the SDK says this call did not succeed.

    Deliberately narrow, because the alternative errs the expensive way. Two
    conditions only:
      - is_error on the ResultMessage: unambiguous, the CLI is telling us the
        call failed (a 429/5xx surfaces here);
      - no text at all: an empty reply is a delivery failure, not a model that
        chose to say nothing. It used to reach json.loads and be retried three
        times by the VALIDATION loop as though the model had answered badly.

    A turn ceiling is reported in the message but does NOT by itself raise: an
    agent can legitimately use every turn and still emit a valid final answer,
    and raising on that would fail runs that currently work. `stop_reason` and
    `num_turns` are read with getattr because they vary across SDK versions —
    a missing attribute must not turn a real failure into an AttributeError.
    """
    if result_message is None:
        return
    is_error = bool(getattr(result_message, "is_error", False))
    if not is_error:
        return
    stop = getattr(result_message, "stop_reason", None)
    turns = getattr(result_message, "num_turns", None)
    detail = f"is_error=True stop_reason={stop!r} num_turns={turns!r}"
    if caps is not None and getattr(caps, "max_turns", None):
        detail += f" max_turns={caps.max_turns}"
    raise TransportFailure(
        f"the SDK reported this call FAILED ({detail}). This is a transport or "
        "turn-budget failure, not a malformed model reply — it is raised rather "
        "than parsed so it is not retried as a schema error.")


class SchemaValidationError(Exception):
    """Raised internally when a reply fails schema validation; carries the message re-sent to the model."""


def validate_schema(data: Any, schema: dict) -> None:
    """Check `data` against a small hand-rolled schema dict.

    schema = {
        "required": ["field_a", "field_b"],
        "enums": {"field_b": ["exit"]},   # optional: field_b must be one of these values
    }
    Raises SchemaValidationError with a human-readable reason on failure.
    """
    if not isinstance(data, dict):
        raise SchemaValidationError("reply must be a JSON object")

    for field in schema.get("required", []):
        if field not in data:
            raise SchemaValidationError(f"missing required field: {field}")

    for field, allowed in schema.get("enums", {}).items():
        if field in data and data[field] not in allowed:
            raise SchemaValidationError(
                f"field {field!r} must be one of {allowed}, got {data[field]!r}"
            )


async def _ask_once(
    system_prompt: str, user_turn: str, model: str,
    capabilities: "Capabilities" = None, action_trail: list = None,
    stage_name: str = "unknown",
) -> str:
    """Send one isolated turn (or, under a tool-bearing profile, one bounded
    agentic loop) to `model` and return its final text reply.

    When `action_trail` is provided it is filled with every tool use and tool
    result observed. That is not optional bookkeeping: a sealed call is fully
    described by its assembled input, so the transcript alone reproduces it,
    but a tool-bearing call does things the input does not determine. Without
    the trail, "transcripts are write-only evidence" would quietly become
    false the moment a stage was given a tool — the audit trail would name the
    question and lose the entire investigation.
    """
    caps = capabilities or SEALED
    # Step 16.6 chunk 2: record the ATTEMPT before the SDK call fires, so a
    # transport failure mid-stream still leaves a trace in the meter.
    cost_meter.record_attempt("model_call")
    # Item A: when the dispatching director set a move token allowance, derive
    # this tooled call's turn ceiling from what remains (layer 2) and arm the
    # in-stream tracker that denies tools once the room is gone (layer 1). No
    # allowance (the default) leaves every path byte-identical.
    tracker = None
    effective_max_turns = caps.max_turns
    allowance = _move_token_allowance() if caps.uses_tools else None
    if allowance is not None:
        remaining = max(1, allowance - _face_value_spent())
        effective_max_turns = _derive_granted_turns(remaining, caps.max_turns)
        tracker = _MoveBudgetTracker(remaining, effective_max_turns)
        if effective_max_turns < caps.max_turns:
            print(f"TOKEN_ALLOWANCE stage={stage_name} remaining={remaining:,} "
                  f"tokens -> max_turns {effective_max_turns} "
                  f"(profile ceiling {caps.max_turns})")
    guard_kwargs = {}
    if caps.uses_tools:
        # The guard consults every tool call before it runs. Sealed calls make
        # no tool calls, so attaching it there would be dead weight.
        #
        # TWO DELIVERIES, ONE POLICY. can_use_tool is the SDK's replacement for
        # the permission PROMPT and is documented as NOT invoked for anything
        # already on allowed_tools — which is every tool in the profile, i.e.
        # exactly the Bash/Write/Edit the guard exists for. The PreToolUse hook
        # is the one the SDK says gates *every* tool call, so it is the gate;
        # the callback stays for anything that somehow reaches an "ask".
        can_use = capability_guard.make_can_use_tool(stage_name)
        hook = capability_guard.make_pre_tool_use_hook(stage_name)
        if tracker is not None:
            can_use = _wrap_can_use_tool_with_allowance(can_use, tracker, stage_name)
            hook = _wrap_hook_with_allowance(hook, tracker, stage_name)
        guard_kwargs["can_use_tool"] = can_use
        # matcher=None matches every tool name; hooks require streaming mode,
        # which a tool-bearing call already uses (see the prompt_arg block).
        guard_kwargs["hooks"] = {"PreToolUse": [HookMatcher(matcher=None,
                                                            hooks=[hook])]}
    # Optional MCP connectors: extra allowed tools (mcp__<name>) plus the
    # mcp_servers/strict_mcp_config kwargs, empty unless mcp_servers.json exists.
    mcp_kwargs, mcp_allowed = _mcp_option_kwargs(caps.uses_tools)
    options = ClaudeAgentOptions(
        model=model,
        system_prompt=system_prompt,
        allowed_tools=list(caps.allowed_tools) + mcp_allowed,
        # Everything not explicitly granted stays blocked, so a widened profile
        # can never silently inherit a tool nobody listed.
        disallowed_tools=[t for t in _DISALLOWED_TOOLS if t not in caps.allowed_tools],
        setting_sources=[],
        max_turns=effective_max_turns,
        **guard_kwargs,
        # Per-run workspace: an isolated cwd (+ PYTHONPATH to the repo root) when
        # the caller wrapped this in agent_workspace(); {} otherwise, so the
        # default-cwd path is unchanged.
        **_workspace_option_kwargs(caps.uses_tools),
        # Configured MCP connectors (a CAD tool, a domain API, …); {} unless
        # mcp_servers.json is present, so the no-connector path is unchanged.
        **mcp_kwargs,
    )
    # The SDK requires STREAMING input (an AsyncIterable) whenever a
    # can_use_tool callback is attached — a bare string prompt is rejected with
    # "can_use_tool callback requires streaming mode". Sealed calls have no
    # callback and keep the plain string path unchanged. For tool-bearing calls
    # we wrap the single user turn in a one-message stream that mirrors the exact
    # envelope the SDK builds for a string prompt; stream_input ends input when
    # the generator is exhausted, so the bounded agentic loop still runs once.
    prompt_arg = user_turn
    if caps.uses_tools:
        async def _single_turn_stream():
            yield {
                "type": "user",
                "message": {"role": "user", "content": user_turn},
                "parent_tool_use_id": None,
                "session_id": "",
            }
        prompt_arg = _single_turn_stream()

    parts: list[str] = []
    result_usage = None
    result_message = None
    async for message in query(prompt=prompt_arg, options=options):
        if isinstance(message, AssistantMessage):
            if tracker is not None:
                # Item A layer 1: one turn observed, with real usage when the
                # SDK reports it. The can_use_tool wrapper reads this state.
                # message_id is what makes a TURN a turn: the SDK yields one
                # AssistantMessage per content block, all sharing one id and one
                # usage (see note_assistant_message).
                tracker.note_assistant_message(
                    getattr(message, "usage", None),
                    getattr(message, "message_id", None))
            for block in message.content:
                if isinstance(block, TextBlock):
                    parts.append(block.text)
                elif action_trail is not None and isinstance(block, ToolUseBlock):
                    action_trail.append({
                        "kind": "tool_use",
                        "tool": block.name,
                        "input": _bounded(block.input),
                    })
        elif isinstance(message, UserMessage) and action_trail is not None:
            # Tool RESULTS arrive as user-role messages. They are bounded here
            # because a raw result (a full web page, a directory listing) is
            # exactly the unbounded tool output the architecture forbids from
            # reaching any downstream reader.
            content = message.content
            if isinstance(content, list):
                for block in content:
                    if isinstance(block, ToolResultBlock):
                        action_trail.append({
                            "kind": "tool_result",
                            "content": _bounded(block.content),
                        })
        elif isinstance(message, ResultMessage):
            result_usage = message.usage
            result_message = message
    # Step 16.6: the ONE observing touch at this door — count the completed
    # call (+ SDK-reported usage) into the shared cost meter. Observation
    # only; the return value is untouched. Item C (2026-07-28): the SDK's own
    # correctly-priced total_cost_usd and the call's num_turns ride along —
    # read with getattr because they vary across SDK versions, and the meter
    # type-guards them, so a missing attribute can never sink a call.
    cost_meter.record_call(
        "model_call", result_usage,
        cost_usd=getattr(result_message, "total_cost_usd", None),
        num_turns=getattr(result_message, "num_turns", None),
    )
    # A TRANSPORT FAILURE IS NOT A BAD MODEL REPLY. Only `usage` was read off the
    # ResultMessage, so is_error and a max-turns stop were invisible: a 429/5xx
    # surfaced by the CLI, or an agentic loop that hit its turn ceiling, returned
    # whatever text had accumulated — often "" or mid-loop narration. That fell
    # through to json.loads, so the VALIDATION loop retried it (three more
    # attempts, each a full 200-turn agentic run under a FULL profile), the meter
    # counted every one as completed, and the final error read "model reply failed
    # schema validation after 3 attempts" — a sentence about the model, for a
    # failure of the transport or the turn budget.
    #
    # Raising here routes it to _transport_with_retry instead, which is the code
    # that knows the difference (and knows a TOOLED call is not idempotent, so it
    # does not blindly replay one).
    _raise_if_transport_failed(result_message, caps)
    if not any(p.strip() for p in parts):
        raise TransportFailure(
            "the call returned NO TEXT at all. An empty reply is a delivery "
            "failure, not an answer — parsing it produced a JSONDecodeError that "
            "the validation loop then retried as though the model had replied "
            "badly, three times, each a full agentic run under a tool profile.")
    # Under a tool profile the model's LAST text block is its answer; earlier
    # blocks are narration between tool calls and would corrupt the JSON parse
    # if concatenated. A sealed call has exactly one block, so joining and
    # taking the last are identical there — the default path is unchanged.
    if caps.uses_tools and parts:
        return parts[-1].strip()
    return "".join(parts).strip()


MAX_TRAIL_CHARS = 2000


def _bounded(value) -> str:
    """Render any tool input/result as a bounded string for the action trail."""
    try:
        text = value if isinstance(value, str) else json.dumps(value, default=str)
    except (TypeError, ValueError):
        text = str(value)
    if len(text) <= MAX_TRAIL_CHARS:
        return text
    return text[:MAX_TRAIL_CHARS] + f" [...truncated, {len(text)} chars total]"


# Backoff before transport retry 1 and retry 2 (Step 16: initial attempt +
# at most 2 retries; the Step-15 crashed demo proved an SDK exception used
# to propagate uncaught).
TRANSPORT_RETRY_BACKOFFS = (2.0, 5.0)


def _invoke_transport(
    system_prompt: str, user_turn: str, model: str,
    capabilities: "Capabilities" = None, action_trail: list = None,
    stage_name: str = "unknown",
) -> str:
    """The ONE SDK invocation seam — exactly the old asyncio.run(_ask_once(...))
    call site, factored out (Step 16, disclosed) so tests can substitute a
    fake transport by patching this function.

    capabilities/action_trail are keyword-optional and default to the sealed
    behavior, so every existing fake transport with the three-argument
    signature keeps working untouched."""
    return asyncio.run(
        _ask_once(system_prompt, user_turn, model, capabilities, action_trail,
                  stage_name)
    )


def _seam_accepts_capabilities() -> bool:
    """True when the current _invoke_transport can take the capability
    arguments. Recomputed per call because the seam is monkeypatched at
    runtime; a cached answer would be wrong for the next test."""
    try:
        params = inspect.signature(_invoke_transport).parameters
    except (TypeError, ValueError):
        return False
    if any(p.kind is inspect.Parameter.VAR_POSITIONAL for p in params.values()):
        return True
    return "capabilities" in params


def _append_run_log(stage_input, line: str) -> None:
    """Append one durable line to runs/<run_id>/log.txt. BEST EFFORT — never
    raises, because every caller is on a path where a failure to LOG must not
    become a failure to RUN.

    This was three copies of `open(Path("runs")/run_id/"log.txt", "a")` with no
    mkdir and no guard, inside _log_fence_note, _log_reask and
    _log_transport_retry. All three are called from INSIDE the attempt loop, so a
    run_id whose directory does not exist — a side door, a harness id, a process
    started from another cwd — raised FileNotFoundError and took the run down.
    _log_fence_note made that acute: it fires on the FIRST FENCED REPLY, and
    CLAUDE.md's own fence watch records Sonnet and Haiku fencing at ~100%. So the
    failure mode was "the run dies on its first model reply", from the logging.

    Their docstrings all describe this as best-effort ("printed but cannot be
    durably logged"), which is the behaviour they now actually have. The line is
    always printed by the caller first, so nothing is lost from the terminal even
    when the durable write fails.
    """
    run_id = stage_input.get("run_id") if isinstance(stage_input, dict) else None
    if not run_id:
        return
    try:
        run_dir = Path("runs") / str(run_id)
        run_dir.mkdir(parents=True, exist_ok=True)
        with open(run_dir / "log.txt", "a") as f:
            f.write(line + "\n")
    except OSError:
        # Disk full, permissions, a path that is not a directory. The terminal
        # already has the line; losing the durable copy is strictly better than
        # losing the run.
        pass


def _log_transport_retry(stage_name: str, stage_input: dict, retry_number: int, exc: Exception) -> None:
    """Durably record one transport retry the moment it is decided.

    Same run-dir derivation and same bare-call limitation as RE-ASK lines:
    run_id from stage_input; without one, the line is printed but cannot be
    durably logged."""
    first_line = str(exc).splitlines()[0] if str(exc) else ""
    line = (
        f"TRANSPORT-RETRY stage={stage_name} retry={retry_number} "
        f"exception={type(exc).__name__}: {first_line}"
    )
    print(line)
    _append_run_log(stage_input, line)


def _transport_with_retry(
    stage_name: str, stage_input: dict, system_prompt: str, user_turn: str, model: str,
    capabilities: "Capabilities" = None, action_trail: list = None,
) -> str:
    """Bounded transport retry around _invoke_transport (Step 16).

    Catches Exception from the transport/SDK layer ONLY — our own
    SchemaValidationError and json.JSONDecodeError are raised later, in
    parsing/validation, and never enter this path. Initial attempt plus at
    most len(TRANSPORT_RETRY_BACKOFFS) retries with short backoff; each
    retry writes a durable TRANSPORT-RETRY line; exhaustion re-raises the
    original exception unwrapped. The validation re-ask counter is
    UNTOUCHED: transport retries correct DELIVERY, the validation loop
    corrects CONTENT — the two bounds never interact."""
    # A TOOLED call is NOT idempotent: it may already have written files or run
    # commands before the transport died, and blindly replaying the whole
    # agentic loop would re-commit every one of those side effects with nothing
    # rolling them back or even noticing. A sealed call has no side effects, so
    # it keeps the full retry budget it has always had.
    tooled = capabilities is not None and capabilities is not SEALED and capabilities.uses_tools
    budget = 0 if tooled else len(TRANSPORT_RETRY_BACKOFFS)

    for transport_try in range(1 + budget):
        try:
            # The seam is patched by fakes throughout the test suite, and
            # those fakes were written against the historical 3-argument
            # signature. Pass only what the current callable actually accepts,
            # so adding capabilities did not silently invalidate every
            # contract test by making it raise TypeError instead of asserting.
            if _seam_accepts_capabilities():
                return _invoke_transport(
                    system_prompt, user_turn, model, capabilities, action_trail,
                    stage_name,
                )
            return _invoke_transport(system_prompt, user_turn, model)
        except Exception as exc:
            if transport_try == budget:
                raise
            _log_transport_retry(stage_name, stage_input, transport_try + 1, exc)
            time.sleep(TRANSPORT_RETRY_BACKOFFS[transport_try])
    raise RuntimeError("unreachable")  # loop always returns or raises


def strip_fence(reply: str) -> tuple[str, bool]:
    """Detect and remove a surrounding ``` code fence. Pure function, no I/O.

    Returns (stripped_text, was_fenced). Stripping is exactly the tolerance
    the old in-parse version applied: trim whitespace, strip backticks off
    both ends, drop a leading "json" language tag, trim again. Detection is
    separated from JSON parsing so a fence can be recorded whether or not
    the reply then parses.
    """
    text = reply.strip()
    was_fenced = text.startswith("```")
    if was_fenced:
        text = text.strip("`")
        if text.startswith("json"):
            text = text[4:]
        text = text.strip()
    return text, was_fenced


def extract_single_fenced_block(reply: str) -> str | None:
    """Single-fence prose tolerance (17-CLOSE). Pure function, no I/O.

    When a reply contains EXACTLY one ``` fenced block, return the block's
    content (a leading language tag like ```json dropped), with leading and
    trailing prose around the fence tolerated. No fence or multiple fences
    return None, so the caller keeps its existing failure path untouched.
    Provenance: the Step-22 smoke crash (runs/smoke6-20260711T083510Z in the
    build-22 worktree) — reflect replies wrapped their JSON in prose plus one
    fence and burned the whole re-ask budget; strip_fence only handles a
    reply that IS a fence, not one that CONTAINS a fence.
    """
    if reply.count("```") != 2:
        return None
    inner = reply.split("```", 2)[1]
    first_line, newline, rest = inner.partition("\n")
    if newline and re.fullmatch(r"[A-Za-z0-9_+-]*", first_line.strip()):
        inner = rest
    return inner.strip()


def extract_json_object(reply: str) -> str | None:
    """Prose-wrapped-object tolerance. Pure function, no I/O.

    A FULL/tooled agent that does real work NARRATES, then emits its JSON with
    no fence — 'Both methods agree.\\n\\n{...}'. strip_fence and
    extract_single_fenced_block only handle fences, so such a reply burns the
    whole re-ask budget (first seen live: the free_experimenter Collatz run,
    2026-07-23). Return the substring of the LAST top-level {...} in the reply
    that parses as JSON, or None. Uses json.JSONDecoder.raw_decode so braces
    inside strings are handled correctly; 'last wins' picks the final result
    object when prose earlier in the reply also contains a JSON-looking span.
    """
    candidates = extract_json_objects(reply)
    return candidates[-1] if candidates else None


def extract_json_objects(reply: str) -> list:
    """EVERY top-level {...} in the reply that parses as JSON, in order.

    POSITION IS THE WRONG TIE-BREAK, IN BOTH DIRECTIONS. "Last wins" exists
    because prose BEFORE the answer can contain a JSON-looking span. But it
    fails the mirror case: an agent that finishes by restating its schema, or
    quoting an example, hands back that trailing object instead of its result.
    Verified: a reply ending "For reference the schema is {"summary": "string"}"
    returned the schema — so the real answer was discarded and the stage re-asked
    with a bogus "missing required field", which for a FULL profile costs another
    200-turn agentic run.
    Neither first nor last is right. The caller knows the SCHEMA, so it can pick
    the candidate that actually satisfies the requirement instead of guessing by
    position — see _select_json_candidate. This function just enumerates them.

    Uses json.JSONDecoder.raw_decode, so braces inside strings are handled.
    """
    decoder = json.JSONDecoder()
    found = []
    idx = 0
    while True:
        start = reply.find("{", idx)
        if start == -1:
            break
        try:
            _obj, end = decoder.raw_decode(reply, start)
            found.append(reply[start:end])
            idx = end
        except json.JSONDecodeError:
            idx = start + 1
    return found


#: Words a model uses when it is DESCRIBING a field rather than filling it in.
#: A schema restatement carries these as its values; an answer carries data.
_TYPE_WORDS = frozenset({
    "string", "str", "text", "int", "integer", "number", "float", "bool",
    "boolean", "list", "array", "object", "dict", "null", "none", "any",
    "list of strings", "list[str]", "number or short string",
})


def _looks_like_schema_echo(obj) -> bool:
    """True when every value in `obj` names a TYPE or is an angle-bracket
    placeholder, i.e. this is the model repeating the schema back rather than
    answering.

    Needed because a restatement satisfies required-key presence — it has all
    the right KEYS, which is what makes it indistinguishable to validate_schema
    (that checks required fields and enums, neither of which discriminates
    `{"summary": "string"}` from a real summary). The tell is the VALUES.

    Deliberately conservative: EVERY value must look like a description, so a
    real answer that happens to contain the word "string" in one field is never
    mistaken for an echo. An empty object is not an echo — it is just empty, and
    the schema check should be the thing that rejects it.
    """
    if not isinstance(obj, dict) or not obj:
        return False
    for value in obj.values():
        if isinstance(value, str):
            v = value.strip().lower()
            if v in _TYPE_WORDS or (v.startswith("<") and v.endswith(">")):
                continue
        return False
    return True


def _select_json_candidate(reply: str, schema: dict):
    """The parsed object among the reply's JSON spans that best satisfies
    `schema`, or None when the reply carries no JSON at all.

    Preference order, last-first so a trailing answer still wins over leading
    narration (the case "last wins" was written for):
      1. carries every required key AND is not a schema echo — the answer;
      2. carries every required key — better than nothing when every candidate
         reads like an echo;
      3. the last that parses at all, so a genuinely malformed reply gets exactly
         the behaviour and the error message it got before.
    """
    candidates = extract_json_objects(reply)
    if not candidates:
        return None
    required = (schema or {}).get("required") or []
    if required:
        parsed = []
        for text in candidates:
            try:
                parsed.append((text, json.loads(text)))
            except ValueError:
                continue
        complete = [(t, o) for t, o in parsed
                    if isinstance(o, dict) and all(k in o for k in required)]
        for text, obj in reversed(complete):
            if not _looks_like_schema_echo(obj):
                return text
        if complete:
            return complete[-1][0]
    return candidates[-1]


def _log_fence_note(stage_name: str, stage_input: dict) -> None:
    """Durably record a fenced reply the moment it is seen, before any parse.

    Same durable path and same limitation as _log_reask: the run log is
    runs/<run_id>/log.txt with run_id taken from stage_input; without a
    run_id the NOTE is printed but cannot be durably logged. The line format
    matches what log_stage_call used to write, so the fence watch keeps
    counting the same string — but now every fenced reply is counted, not
    only the ones that went on to parse."""
    line = f"NOTE stage={stage_name} fence_stripped — reply arrived wrapped in a ``` code fence"
    print(line)
    _append_run_log(stage_input, line)


_TRANSCRIPT_SEQ = 0

# Reflection runs its review chain through a ThreadPoolExecutor, so the
# sequence counter is touched concurrently. Without the lock two threads take
# the same number and one write-before-call transcript overwrites another.
_TRANSCRIPT_SEQ_LOCK = threading.Lock()


def _next_transcript_seq() -> int:
    """Claim the next per-process transcript sequence number, atomically."""
    global _TRANSCRIPT_SEQ
    with _TRANSCRIPT_SEQ_LOCK:
        _TRANSCRIPT_SEQ += 1
        return _TRANSCRIPT_SEQ


def _write_transcript(
    stage_name: str,
    system_prompt: str,
    stage_input: dict,
    stage_input_serialized: str,
    model: str,
    capabilities: "Capabilities" = SEALED,
) -> Optional[int]:
    """Write the fully assembled model input to runs/<run_id>/transcripts/.

    Called immediately after the model input is assembled and BEFORE the
    model is called, so a crashed call still leaves its transcript. One file
    per call, named <zero-padded per-process sequence>_<stage_name>.json —
    unique and sortable in call order. Contents are exactly
    {stage_name, model, timestamp_utc, system_prompt, stage_input_serialized},
    where stage_input_serialized is the byte-for-byte string sent to the
    model. The transcript captures the attempt-1 assembled input; re-ask
    additions on attempts 2+ are already durably captured verbatim by RE-ASK
    lines in log.txt, so attempt-2+ inputs are reconstructible from this file
    plus those lines.

    Transcripts are WRITE-ONLY evidence: no code path in the project may read
    a transcript back into any model input or any stage logic. Run-dir
    derivation is the same single source of truth as _log_reask /
    _log_fence_note: run_id from stage_input; a bare call without run_id
    writes no transcript.

    Returns the sequence number it claimed (None when no transcript was
    written). The caller MUST thread that number into _append_action_trail —
    re-reading the global there would name a different call's file whenever
    reviews run concurrently.
    """
    run_id = stage_input.get("run_id") if isinstance(stage_input, dict) else None
    if not run_id:
        return None
    seq = _next_transcript_seq()
    transcripts_dir = Path("runs") / str(run_id) / "transcripts"
    transcripts_dir.mkdir(parents=True, exist_ok=True)
    record = {
        "stage_name": stage_name,
        "model": model,
        "timestamp_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "system_prompt": system_prompt,
        "stage_input_serialized": stage_input_serialized,
        # The profile is part of the evidence: the same input under SEALED and
        # under BUILDER are different experiments, and a reader who cannot tell
        # them apart cannot judge the result.
        "capabilities": capabilities.name,
        "allowed_tools": list(capabilities.allowed_tools),
        "max_turns": capabilities.max_turns,
    }
    with open(transcripts_dir / f"{seq:04d}_{stage_name}.json", "w") as f:
        json.dump(record, f, indent=2)
    return seq


def _append_action_trail(
    stage_name: str, stage_input: dict, attempt: int, trail: list,
    seq: Optional[int] = None,
) -> None:
    """Append one attempt's tool-use trail beside its transcript.

    A separate <seq>_<stage>.actions.json rather than a rewrite of the
    transcript, because the transcript is written BEFORE the call and that
    write-first property is what makes it survive a crash. Rewriting it
    afterwards would trade a guarantee for tidiness.

    Still write-only evidence: nothing in the project may read these back into
    a model input or stage logic.

    `seq` is the number _write_transcript claimed for THIS call. It is passed
    in rather than re-read from the global because the global has moved on by
    the time an agentic loop returns whenever other reviews are running in
    parallel — the trail would then be filed against someone else's call.
    """
    run_id = stage_input.get("run_id") if isinstance(stage_input, dict) else None
    if not run_id or seq is None:
        return
    transcripts_dir = Path("runs") / str(run_id) / "transcripts"
    transcripts_dir.mkdir(parents=True, exist_ok=True)
    path = transcripts_dir / f"{seq:04d}_{stage_name}.actions.json"
    existing = []
    if path.is_file():
        try:
            existing = json.loads(path.read_text())
        except (ValueError, OSError):
            existing = []
    existing.append({"attempt": attempt, "actions": trail})
    with open(path, "w") as f:
        json.dump(existing, f, indent=2)
    tools_used = [a["tool"] for a in trail if a.get("kind") == "tool_use"]
    line = (
        f"ACTIONS stage={stage_name} attempt={attempt} "
        f"tool_calls={len(tools_used)} tools={sorted(set(tools_used))}"
    )
    print(line)
    # Same best-effort path as the other durable lines: this one is reached after
    # a tooled call has already done real work, so failing to log its trail must
    # never discard that work. (_append_action_trail's own mkdir above covers the
    # transcript dir; this covers the run log beside it.)
    _append_run_log(stage_input, line)


def _log_reask(stage_name: str, stage_input: dict, attempt: int, error: str) -> None:
    """Durably record a re-ask the moment it is triggered.

    Appends one line to the same run log log_stage_call writes to
    (runs/<run_id>/log.txt), with the verbatim error JSON-encoded so
    multi-line errors stay on one log line. The run_id comes from
    stage_input — every stage's input carries it, and it is the only
    run-identifying thing this function is allowed to see. If stage_input
    carries no run_id (e.g. a bare unit-test call), the line is printed
    but cannot be durably logged.
    """
    line = f"RE-ASK stage={stage_name} attempt={attempt} error={json.dumps(error)}"
    print(line)
    _append_run_log(stage_input, line)


def call_stage_model(
    stage_name: str,
    system_prompt: str,
    stage_input: dict,
    schema: dict,
    model: str = TRIAGE_MODEL,
    extra_validator: Optional[Callable[[dict], list[str]]] = None,
    capabilities: "Capabilities" = SEALED,
) -> tuple[dict, dict]:
    """Call `model` for one stage, enforcing isolation and schema, with bounded re-asks.

    `model` defaults to Haiku so stages 2-6 behave byte-identically without
    passing it. `extra_validator`, if given, is a callable parsed_json ->
    list of plain-language error strings (empty = valid); it runs only after
    schema validation passes, and a non-empty list is treated exactly like a
    schema failure — the errors are re-asked within the same bounded loop.
    Returns (validated_dict, timing_info) where timing_info is
    {"model": ..., "duration_seconds": ..., "attempts": N, "fence_stripped": bool}.
    Raises RuntimeError after MAX_ATTEMPTS total failed attempts.
    """
    # Enforced BEFORE anything else: a stage whose role forbids tools must not
    # even assemble a tooled call. Raises CapabilityPairingError.
    capability_guard.assert_profile_allowed(stage_name, capabilities.name)

    start = time.monotonic()
    user_turn = json.dumps(stage_input)
    # The input is now fully assembled; record it verbatim before the call.
    transcript_seq = _write_transcript(stage_name, system_prompt, stage_input,
                                       user_turn, model, capabilities)
    last_error = ""
    # Filled by the transport under a tool profile; appended to the transcript
    # after the call so the evidence covers what the stage DID, not only what
    # it was asked. Stays empty (and unwritten) for a sealed call.
    action_trail: list = []
    # The wind-up observer fires inside the SDK stream, far below any function
    # that can see stage_input, and it must leave a durable line. Published here
    # (where the run_id IS in scope) and cleared in the finally below, so a bare
    # call or a crash cannot leave a stale id pointing at the wrong run's log.
    global _CURRENT_RUN_ID
    _previous_run_id = _CURRENT_RUN_ID
    _CURRENT_RUN_ID = (stage_input.get("run_id")
                       if isinstance(stage_input, dict) else None)
    try:
        return _call_stage_model_attempts(
            stage_name, system_prompt, stage_input, schema, model,
            extra_validator, capabilities, start, user_turn, transcript_seq,
            last_error, action_trail)
    finally:
        _CURRENT_RUN_ID = _previous_run_id


def _call_stage_model_attempts(
    stage_name, system_prompt, stage_input, schema, model, extra_validator,
    capabilities, start, user_turn, transcript_seq, last_error, action_trail,
) -> tuple[dict, dict]:
    """call_stage_model's bounded attempt loop, unchanged — split out ONLY so the
    run-id publication above can wrap it in try/finally without re-indenting the
    whole body (which would bury a one-line change in a hundred-line diff)."""
    for attempt in range(1, MAX_ATTEMPTS + 1):
        # Item A layer 3: never START an attempt (including a validation
        # re-ask) on an allowance that is already spent — a re-ask under a
        # FULL profile is another whole agentic run. No-op without the env
        # var. Raises TokenAllowanceExhausted, which the supervisor journals
        # as an honest halted_token_allowance run_record.
        _raise_if_allowance_exhausted(stage_name, attempt)
        if attempt > 1:
            user_turn = json.dumps(
                {"original_input": stage_input, "validation_error": last_error}
            )

        reply = _transport_with_retry(
            stage_name, stage_input, system_prompt, user_turn, model,
            capabilities, action_trail,
        )
        if action_trail:
            _append_action_trail(stage_name, stage_input, attempt, action_trail,
                                 seq=transcript_seq)
            action_trail = []
        # Step 18.7: attribute this COMPLETED call to its stage (the door-level
        # record_call cannot see stage_name). Observation only.
        cost_meter.record_stage_call(stage_name)

        text, fence_stripped = strip_fence(reply)
        if fence_stripped:
            # Recorded here, BEFORE any parse attempt, so a fenced reply that
            # then fails to parse is still counted (the Step-10 undercount).
            _log_fence_note(stage_name, stage_input)

        try:
            try:
                data = json.loads(text)
            except json.JSONDecodeError:
                # 17-CLOSE single-fence tolerance: the current parse path
                # above is unchanged; only on ITS failure, a reply carrying
                # exactly one fenced block is retried as that block's
                # content (prose around the fence tolerated). None means no
                # rescue — re-raise the original error, existing behavior.
                block = extract_single_fenced_block(reply)
                if block is None:
                    # No fence — a full/tooled agent narrated then emitted raw
                    # JSON. Extract the embedded object (prime-directive reality:
                    # a free agent that does real work explains itself). None =>
                    # no rescue, re-raise (existing behavior).
                    #
                    # SCHEMA-AWARE, not position-aware: when a reply holds more
                    # than one JSON span — narration before the answer, or a
                    # schema restatement after it — the one carrying the required
                    # keys is the answer. Guessing by position discarded a real
                    # result and burned another agentic attempt on a bogus
                    # "missing required field".
                    block = _select_json_candidate(reply, schema)
                if block is None:
                    raise
                data = json.loads(block)
            validate_schema(data, schema)
            if extra_validator is not None:
                extra_errors = extra_validator(data)
                if extra_errors:
                    raise SchemaValidationError(" ".join(extra_errors))
        except (json.JSONDecodeError, SchemaValidationError) as e:
            last_error = f"{e} (raw reply: {reply!r})"
            if attempt < MAX_ATTEMPTS:
                # A re-ask is now certain: persist the correction verbatim so a
                # success-after-re-ask still leaves a recoverable record, and
                # count the REJECT into the stage-keyed meter (Step 18.7 —
                # observation only; the loop's behavior is unchanged).
                cost_meter.record_reject(stage_name)
                _log_reask(stage_name, stage_input, attempt, last_error)
            continue

        duration = time.monotonic() - start
        timing_info = {
            "model": model,
            "duration_seconds": round(duration, 3),
            "attempts": attempt,
            "fence_stripped": fence_stripped,
            "capabilities": capabilities.name,
        }
        return data, timing_info

    duration = time.monotonic() - start
    raise RuntimeError(
        f"stage {stage_name!r}: model reply failed schema validation after "
        f"{MAX_ATTEMPTS} attempts ({duration:.3f}s). Last error: {last_error}"
    )


